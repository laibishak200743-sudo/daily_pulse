export function getLocalizedBadge(badgeId: string, language: SupportedLanguage, fallbackTitle: string, fallbackDesc: string, fallbackCriteria: string) {
  const trans = BADGE_TRANSLATIONS[badgeId]?.[language];
  if (trans) {
    return {
      title: trans.title,
      desc: trans.desc,
      criteria: trans.criteria,
    };
  }
  return {
    title: fallbackTitle,
    desc: fallbackDesc,
    criteria: fallbackCriteria,
  };
}
