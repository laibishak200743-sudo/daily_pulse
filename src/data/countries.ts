export interface CountryItem {
  code: string;       // ISO 3166-1 alpha-2 code (e.g., 'DZ', 'US', 'SA')
  name: string;       // Standard English name (e.g., 'Algeria', 'United States')
  nameAr: string;     // Localized Arabic name (e.g., 'الجزائر', 'الولايات المتحدة')
  flag: string;       // Unicode flag emoji (e.g., '🇩🇿', '🇺🇸')
}

export function getFlagEmoji(countryCode: string): string {
  if (!countryCode || countryCode.length !== 2) return '🌐';
  const codePoints = countryCode
    .toUpperCase()
    .split('')
    .map((char) => 127397 + char.charCodeAt(0));
  return String.fromCodePoint(...codePoints);
}

