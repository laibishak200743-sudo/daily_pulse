export function findCountry(codeOrName: string): CountryItem | undefined {
  if (!codeOrName) return undefined;
  const q = codeOrName.trim().toLowerCase();
  return WORLD_COUNTRIES.find(
    (c) =>
      c.code.toLowerCase() === q ||
      c.name.toLowerCase() === q ||
      c.nameAr.toLowerCase() === q
  );
}

export function searchCountries(query: string): CountryItem[] {
  if (!query || !query.trim()) return WORLD_COUNTRIES;
  const q = query.trim().toLowerCase();
  return WORLD_COUNTRIES.filter(
    (c) =>
      c.name.toLowerCase().includes(q) ||
      c.nameAr.toLowerCase().includes(q) ||
      c.code.toLowerCase().includes(q)
  );
}
